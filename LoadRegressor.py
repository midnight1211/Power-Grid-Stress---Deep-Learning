import torch.nn as nn

class LoadRegressor(nn.Module):
    def __init__(self, input_size):
        super(LoadRegressor, self).__init__()
        self.layers = nn.Sequential(
            nn.Linear(input_size, 64),
            nn.ReLU(),
            nn.Linear(64, 32),
            nn.ReLU(),
            nn.Linear(32, 1)
        )

    def forward(self, x):
        return self.layers(x)